function buildBudgetResult(budget, zone = 'all_high') {
  // Sort catalog by benefit per rupee (highest first)
  const ranked = [...INTERVENTION_CATALOG]
    .map((o) => ({ ...o, efficiency: o.benefit_score / o.unit_cost }))
    .sort((a, b) => b.efficiency - a.efficiency)

  const interventions = []
  let remaining = budget

  // Single pass: for each item (in efficiency order), buy as many units as
  // the remaining budget allows, up to max_units. Skip if none affordable.
  for (const item of ranked) {
    if (remaining < item.unit_cost) continue          // can't afford even 1 unit
    const qty = Math.min(Math.floor(remaining / item.unit_cost), item.max_units)
    if (qty <= 0) continue
    const allocated = qty * item.unit_cost
    interventions.push({
      intervention: item.name,
      spec: item.spec,
      target_location: item.locations[0],
      scope: `${qty} ${item.unit_label}`,             // actual qty bought, not a catalog constant
      quantity: qty,
      unit_cost: item.unit_cost,
      total_cost: allocated,
      benefit_score: item.benefit_score,
    })
    remaining -= allocated
    if (remaining <= 0) break
  }

  const total_cost = budget - remaining
  const plan_id = `OPT-HYD-${budget}-SIMULATED`

  return {
    plan_id,
    budget,
    total_cost,
    remaining_budget: remaining,
    // Guard against divide-by-zero if budget=0
    utilization_pct: budget > 0 ? Math.round((total_cost / budget) * 100) : 0,
    daily_protected_citizens: Math.round((total_cost / 10000) * 460),
    strategy_rationale: `Simulated Demo Allocation: With a budget of ₹${budget.toLocaleString('en-IN')}, prioritizing high-benefit rapid shade installations across surveyed Hyderabad transit corridors.`,
    interventions,
    note: 'Illustrative allocation — costs are estimates. Actual procurement prices may vary.',
  }
}

